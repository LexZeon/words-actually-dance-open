export function normalizeLocale(value) {
  return value === 'en' ? 'en' : 'zh';
}
export function translate(locale, message, values = {}) {
  const text = normalizeLocale(locale) === 'en' ? (EN_MESSAGES[message] ?? message) : message;
  return String(text).replace(/\{(\w+)\}/g, (whole, name) =>
    Object.hasOwn(values, name) ? String(values[name]) : whole,
  );
}

const EN_SOURCE = new Map(Object.entries(EN_MESSAGES).map(([source, english]) => [english, source]));
export function messageSource(text) {
  return Object.hasOwn(EN_MESSAGES, text) ? text : (EN_SOURCE.get(text) ?? null);
}

/** Recognize only application-owned validation templates, preserving quoted user terms. */
